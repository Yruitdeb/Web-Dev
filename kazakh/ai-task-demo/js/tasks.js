function generateTask() {
    const difficulty = document.getElementById("difficulty").value;
    const sphere = document.getElementById("sphere").value;

    const selectedTasks = tasks[difficulty][sphere];

    if (!selectedTasks || selectedTasks.length === 0) {
        document.getElementById("taskOutput").innerText = "No tasks available.";
        return;
    }

    const task = selectedTasks[Math.floor(Math.random() * selectedTasks.length)];

    document.getElementById("taskOutput").innerText =
        `${task}`;
}
